#!/usr/bin/env python3
"""Build a read-only Automotive E/E Evidence execution package.

This experiment composes three already-proven pieces without modifying production:

1. the immutable Screening-to-Evidence probe output;
2. Evidence Tasks generated by `scripts/build_evidence_tasks.py` unchanged;
3. a domain-profiled Evidence prompt/schema contract generated from the production
   Evidence schema shape.

It intentionally does not enter the production acceptance/lifecycle state machine.
The purpose is to determine whether execution-package mechanics can be separated from
edition-specific lifecycle binding before any shared-code refactor is considered.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path
from typing import Any

import profiled_evidence_contract


def load_json(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"{path}: expected JSON object")
    return value


def write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def copy_verified(source: Path, destination: Path, *, expected_sha256: str | None = None, expected_bytes: int | None = None) -> None:
    if not source.is_file():
        raise ValueError(f"required input missing: {source}")
    if expected_sha256 is not None and sha256_file(source) != expected_sha256:
        raise ValueError(f"input SHA mismatch: {source}")
    if expected_bytes is not None and source.stat().st_size != expected_bytes:
        raise ValueError(f"input byte-count mismatch: {source}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, destination)
    if sha256_file(source) != sha256_file(destination) or source.stat().st_size != destination.stat().st_size:
        raise RuntimeError(f"copy verification failed: {destination}")


def build(*, repo_root: Path, probe_root: Path, evidence_profile_path: Path, output_root: Path,
          source_ref: str, source_commit: str) -> dict[str, Any]:
    repo_root = repo_root.resolve()
    probe_root = probe_root.resolve()
    evidence_profile_path = evidence_profile_path.resolve()
    output_root = output_root.resolve()
    if not source_ref.strip():
        raise ValueError("source_ref must be non-empty")
    if len(source_commit) != 40 or any(ch not in "0123456789abcdef" for ch in source_commit):
        raise ValueError("source_commit must be a 40-character lowercase Git SHA")

    bridge_manifest_path = probe_root / "screening-to-evidence-manifest.json"
    task_manifest_path = probe_root / "evidence" / "evidence-task-manifest.json"
    task_index_path = probe_root / "evidence" / "evidence-tasks.jsonl"
    bridge = load_json(bridge_manifest_path)
    task_manifest = load_json(task_manifest_path)
    issue_id = bridge.get("issue_id")
    if not isinstance(issue_id, str) or not issue_id.startswith("SP-"):
        raise ValueError(f"unexpected experiment issue_id: {issue_id!r}")
    if task_manifest.get("issue_id") != issue_id or task_manifest.get("passed") is not True:
        raise ValueError("Evidence Task manifest is not a passing manifest for the bridge issue")
    if bridge.get("shared_evidence_task_builder_modified") is not False:
        raise ValueError("probe no longer establishes unchanged shared Evidence-task builder")

    package_input = output_root / "input"
    tasks_target = package_input / "tasks"
    copy_verified(task_manifest_path, package_input / "evidence-task-manifest.json")
    copy_verified(task_index_path, package_input / "evidence-task-index.jsonl")
    task_records: list[dict[str, Any]] = []
    for entry in task_manifest.get("task_files", []):
        if not isinstance(entry, dict):
            raise ValueError("task_files entries must be objects")
        relative = entry.get("path")
        task_id = entry.get("evidence_task_id")
        if not isinstance(relative, str) or not relative or not isinstance(task_id, str) or not task_id:
            raise ValueError(f"invalid Evidence Task entry: {entry}")
        source = probe_root / "evidence" / relative
        target = tasks_target / Path(relative).name
        copy_verified(source, target, expected_sha256=entry.get("sha256"), expected_bytes=entry.get("bytes"))
        task_records.append({
            "evidence_task_id": task_id,
            "path": f"input/tasks/{target.name}",
            "sha256": sha256_file(target),
            "bytes": target.stat().st_size,
        })
    if len(task_records) != task_manifest.get("evidence_task_count"):
        raise ValueError("copied task count disagrees with Evidence Task manifest")

    contract_root = output_root / "contract-build"
    contract_manifest = profiled_evidence_contract.build(
        repo_root=repo_root,
        profile_path=evidence_profile_path,
        output_root=contract_root,
    )
    final_contract = output_root / "contract"
    for name in ("primary-source-verification-v0.1.md", "evidence-run.schema.json", "evidence-card.schema.json"):
        copy_verified(contract_root / "contract" / name, final_contract / name)
    shutil.rmtree(contract_root)

    profile = load_json(evidence_profile_path)
    if profile.get("issue_id") != issue_id:
        raise ValueError("Evidence profile issue_id mismatch")

    package = {
        "schema_version": "1.0",
        "experiment": "PROFILED_EVIDENCE_EXECUTION_PACKAGE",
        "issue_id": issue_id,
        "source": {
            "ref": source_ref.strip(),
            "commit_sha": source_commit,
        },
        "screening_basis": {
            "pinned_screening_index_sha256": bridge["pinned_input"]["screening_index_sha256"],
            "selection_sha256": bridge["pinned_input"]["selection_sha256"],
            "verification_queue_sha256": bridge["verification_queue"]["sha256"],
            "retained_count": bridge["retained_count"],
        },
        "evidence_tasks": {
            "builder": bridge["shared_evidence_task_builder"],
            "builder_modified": False,
            "manifest_path": "input/evidence-task-manifest.json",
            "manifest_sha256": sha256_file(package_input / "evidence-task-manifest.json"),
            "index_path": "input/evidence-task-index.jsonl",
            "index_sha256": sha256_file(package_input / "evidence-task-index.jsonl"),
            "task_count": len(task_records),
            "tasks": sorted(task_records, key=lambda item: item["evidence_task_id"]),
        },
        "prompt": {
            "prompt_id": contract_manifest["prompt_id"],
            "path": "contract/primary-source-verification-v0.1.md",
            "sha256": sha256_file(final_contract / "primary-source-verification-v0.1.md"),
        },
        "contracts": {
            "profile_id": contract_manifest["profile_id"],
            "artifact_types": contract_manifest["artifact_types"],
            "evidence_run": {
                "path": "contract/evidence-run.schema.json",
                "sha256": sha256_file(final_contract / "evidence-run.schema.json"),
            },
            "evidence_card": {
                "path": "contract/evidence-card.schema.json",
                "sha256": sha256_file(final_contract / "evidence-card.schema.json"),
            },
        },
        "expected_outputs": {
            "one_result_per_task": True,
            "naming": "results/<input task filename>",
            "schema_version": "1.0",
        },
        "rules": [
            "Run primary-source verification independently for each supplied Evidence Task using the pinned prompt and generated strict domain schemas.",
            "Preserve the exact Evidence Task SHA-256 and prompt SHA-256 in every result.",
            "Evidence recommendations remain inputs to later comparison/selection and do not imply article inclusion.",
            "Do not modify the pinned Screening input, selection, Evidence Tasks or source Raw bytes.",
            "This experiment package is read-only and intentionally bypasses production lifecycle acceptance rather than mutating it."
        ],
        "production_ai_pipeline_modified": False,
        "finding": "Execution-package mechanics can compose shared Evidence Tasks with a domain-specific prompt/ontology without changing production AI schemas or the production Evidence lifecycle builder.",
    }
    write_json(output_root / "evidence-execution-package.json", package)
    return package


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", default=".")
    parser.add_argument("--probe-root", required=True)
    parser.add_argument("--evidence-profile", required=True)
    parser.add_argument("--output-root", required=True)
    parser.add_argument("--source-ref", required=True)
    parser.add_argument("--source-commit", required=True)
    args = parser.parse_args()
    repo_root = Path(args.repo_root).resolve()
    profile_path = Path(args.evidence_profile)
    if not profile_path.is_absolute():
        profile_path = repo_root / profile_path
    package = build(
        repo_root=repo_root,
        probe_root=Path(args.probe_root),
        evidence_profile_path=profile_path,
        output_root=Path(args.output_root),
        source_ref=args.source_ref,
        source_commit=args.source_commit,
    )
    print(json.dumps(package, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
