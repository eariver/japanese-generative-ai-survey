def apply_text(text, old, new, pid, bid):
    if old in text:
        assert text.count(old) == 1, (pid, bid, "multi")
        return text.replace(old, new), "fixed"
    if new in text:
        return text, "already-conformant"
    raise AssertionError((pid, bid, old[:60]))


def main() -> int:
    applied = 0
    skipped = 0
    for pid, bid, old, new in FIXES:
        p = f"{D}/{pid}.json"
        s = json.load(open(p))
        if bid in ("deck", "headline"):
            s[bid], st = apply_text(s[bid], old, new, pid, bid)
        else:
            hits = [b for b in s["blocks"] if b["block_id"] == bid]
            assert len(hits) == 1, (pid, bid)
            hits[0]["text"], st = apply_text(hits[0]["text"], old, new, pid, bid)
        if st == "fixed":
            json.dump(s, open(p, "w"), ensure_ascii=False, indent=1)
            open(p, "a").write("\n")
            applied += 1
        else:
            skipped += 1
            print("skip (already conformant):", pid, bid, old[:40])
    print(f"applied {applied}, skipped {skipped} / {len(FIXES)} repairs")
    return 0


